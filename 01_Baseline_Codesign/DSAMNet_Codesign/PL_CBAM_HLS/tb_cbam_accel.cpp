#include "cbam_accel.h"
#include <cstdio>
#include <cstdlib>
#include <cmath>

static bool load_binary(const char *filename, void *buffer, size_t bytes)
{
    FILE *fp = fopen(filename, "rb");
    if (!fp) { printf("ERROR: cannot open %s\n", filename); return false; }
    size_t n = fread(buffer, 1, bytes, fp);
    fclose(fp);
    if (n != bytes) { printf("ERROR: %s expected %zu bytes, got %zu\n", filename, bytes, n); return false; }
    return true;
}

int main()
{
    printf("=== Standalone CBAM accelerator test ===\n");

    static data_t in[DEC_OC*DEC_H*DEC_W];
    static data_t weights[CBAM_WEIGHT_COUNT];
    static data_t after_ca[DEC_OC*DEC_H*DEC_W];
    static data_t out[DEC_OC*DEC_H*DEC_W];

    const char *BASE = "C:/Users/HP/Desktop/BTP_RemoteSensing/DSAMNet";
    char path[512];

    // Real validation: load the ACTUAL decoder output for branch1
    // (already generated by make_decoder_golden.py earlier in this
    // project) as input, and compare our result against the ACTUAL
    // PyTorch cbam0 output on that exact tensor -- not synthetic data.
    static float in_f32[DEC_OC*DEC_H*DEC_W];
    snprintf(path, sizeof(path), "%s/golden_reference/golden_decoder_branch1.bin", BASE);
    if (load_binary(path, in_f32, DEC_OC*DEC_H*DEC_W*sizeof(float))) {
        for (int i = 0; i < DEC_OC*DEC_H*DEC_W; i++) in[i] = data_t(in_f32[i]);
        printf("Loaded real golden_decoder_branch1.bin as input.\n");
    } else {
        printf("Golden input not found, falling back to synthetic data.\n");
        for (int i = 0; i < DEC_OC*DEC_H*DEC_W; i++)
            in[i] = data_t(((i*7) % 20) * 0.2f);
    }
    snprintf(path, sizeof(path), "%s/hls_weights_flat/weights_cbam0_flat.bin", BASE);
    static float tmp[CBAM_WEIGHT_COUNT];
    if (load_binary(path, tmp, CBAM_WEIGHT_COUNT*sizeof(float))) {
        for (int i = 0; i < CBAM_WEIGHT_COUNT; i++) weights[i] = data_t(tmp[i]);
        printf("Loaded real cbam0 weights.\n");
    } else {
        printf("Using synthetic weights instead (real weight file not found).\n");
        for (int i = 0; i < CBAM_WEIGHT_COUNT; i++) weights[i] = data_t(((i%13)-6)*0.05f);
    }

    cbam_accel(in, weights, after_ca, out);

    double sum=0, mn=1e30, mx=-1e30;
    for (int i = 0; i < DEC_OC*DEC_H*DEC_W; i++) {
        double v = (double)out[i];
        sum += v; if (v<mn) mn=v; if (v>mx) mx=v;
    }
    printf("out: min=%f max=%f mean=%f\n", mn, mx, sum/(DEC_OC*DEC_H*DEC_W));

    // Real comparison against PyTorch's actual cbam0 output.
    static float golden[DEC_OC*DEC_H*DEC_W];
    snprintf(path, sizeof(path), "%s/golden_reference/golden_cbam0_branch1.bin", BASE);
    if (load_binary(path, golden, DEC_OC*DEC_H*DEC_W*sizeof(float))) {
        double mae=0, mse=0, maxerr=0;
        double st=0, sg=0, stg=0, st2=0, sg2=0;
        int n = DEC_OC*DEC_H*DEC_W;
        for (int i = 0; i < n; i++) {
            double a = (double)out[i], b = golden[i];
            double e = fabs(a-b);
            mae += e; mse += e*e;
            if (e > maxerr) maxerr = e;
            st+=a; sg+=b; stg+=a*b; st2+=a*a; sg2+=b*b;
        }
        mae /= n; mse = sqrt(mse/n);
        double num = n*stg - st*sg;
        double den = sqrt((n*st2-st*st)*(n*sg2-sg*sg));
        double corr = (den!=0) ? num/den : 0;
        printf("\n[COMPARE vs real PyTorch cbam0 output]\n");
        printf("MAE=%.6f RMSE=%.6f MaxErr=%.6f Corr=%.6f\n", mae, mse, maxerr, corr);
        printf("golden mean=%.6f (expected ~0.0751 per earlier project validation)\n",
               sg/n);
    } else {
        printf("Golden cbam0 output not found -- cannot verify correctness.\n");
    }

    printf("Test complete.\n");
    return 0;
}